"""Build the final 1-minute dataset used by the paper code.

This script merges standardized ACE/L1 solar-wind and VKH GIC tables and writes:

    data/merged_2012_2022_processed.parquet

Expected input tables:

1. Solar wind CSV/parquet with a datetime column and ACE/L1 variables.
   Recognized aliases include:
   Btot/Bx_gse/By_gse/Bz_gse/Vp/Np or common OMNI/CDAWeb-style names.

2. VKH GIC 1-minute parquet generated by download_vkh_gic.py.

The output schema matches the modeling scripts:
Btot, Bx_gse, By_gse, Bz_gse, Vp, Np_filled, P_dyn_nPa, Ey_mV/m, Ma,
epsilon_norm, Newell, Borovsky, density_missing, filled_by_model, gic.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Dict, Iterable

import numpy as np
import pandas as pd


OUTPUT_COLUMNS = [
    "Btot",
    "Bx_gse",
    "By_gse",
    "Bz_gse",
    "Vp",
    "Np_filled",
    "P_dyn_nPa",
    "Ey_mV/m",
    "Ma",
    "epsilon_norm",
    "Newell",
    "Borovsky",
    "density_missing",
    "filled_by_model",
    "gic",
]


ALIASES: Dict[str, Iterable[str]] = {
    "Btot": ["Btot", "B", "Bt", "BF1", "Magnitude", "ABS_B"],
    "Bx_gse": ["Bx_gse", "Bx", "BX_GSE", "BGSEc_x"],
    "By_gse": ["By_gse", "By", "BY_GSE", "BGSEc_y"],
    "Bz_gse": ["Bz_gse", "Bz", "BZ_GSE", "BGSEc_z"],
    "Vp": ["Vp", "V", "Speed", "proton_speed", "V_GSE", "flow_speed"],
    "Np": ["Np", "N", "density", "proton_density", "Np_filled"],
    "gic": ["gic", "GIC", "gic_vyk", "gic_vyk_raw"],
}


def project_root() -> Path:
    return Path(__file__).resolve().parents[2]


def read_table(path: Path) -> pd.DataFrame:
    if path.suffix.lower() in {".parquet", ".pq"}:
        frame = pd.read_parquet(path)
    else:
        frame = pd.read_csv(path)

    if not isinstance(frame.index, pd.DatetimeIndex):
        time_col = next(
            (
                col
                for col in frame.columns
                if str(col).lower() in {"datetime", "timestamp", "time", "date_time", "epoch"}
            ),
            None,
        )
        if time_col is None:
            frame.index = pd.to_datetime(frame.index)
        else:
            frame[time_col] = pd.to_datetime(frame[time_col])
            frame = frame.set_index(time_col)
    frame.index = pd.to_datetime(frame.index).tz_localize(None)
    return frame.sort_index()


def rename_aliases(frame: pd.DataFrame, wanted: Iterable[str]) -> pd.DataFrame:
    rename = {}
    lower_to_original = {str(col).lower(): col for col in frame.columns}
    for standard in wanted:
        if standard in frame.columns:
            continue
        for alias in ALIASES.get(standard, []):
            hit = lower_to_original.get(alias.lower())
            if hit is not None:
                rename[hit] = standard
                break
    return frame.rename(columns=rename)


def to_1min(frame: pd.DataFrame, how: str = "mean") -> pd.DataFrame:
    numeric = frame.apply(pd.to_numeric, errors="coerce")
    if how == "absmax":
        parts = {}
        for col in numeric.columns:
            grouped = numeric[col].groupby(pd.Grouper(freq="1min"))
            parts[col] = grouped.apply(
                lambda x: np.nan if x.dropna().empty else x.iloc[int(np.nanargmax(np.abs(x.to_numpy(dtype="float64"))))]
            )
        return pd.DataFrame(parts)
    return numeric.resample("1min").mean()


def fill_density(np_series: pd.Series) -> tuple[pd.Series, pd.Series, pd.Series]:
    density = pd.to_numeric(np_series, errors="coerce").astype("float32")
    missing = density.isna().astype("int8")
    filled = density.interpolate(limit=5, limit_direction="both")
    filled = filled.ffill(limit=5).bfill(limit=5)
    if filled.isna().any():
        filled = filled.fillna(filled.median())
    filled_by_model = (missing.astype(bool) & filled.notna()).astype("int8")
    return filled.astype("float32"), missing, filled_by_model


def add_solar_coupling(frame: pd.DataFrame) -> pd.DataFrame:
    out = frame.copy()
    out["Np_filled"], out["density_missing"], out["filled_by_model"] = fill_density(out["Np"])

    bt = out["Btot"].abs().astype("float64")
    bz = out["Bz_gse"].astype("float64")
    by = out["By_gse"].astype("float64")
    vp = out["Vp"].abs().astype("float64")
    np_density = out["Np_filled"].astype("float64")
    transverse = np.sqrt(by**2 + bz**2)
    clock = np.arctan2(np.abs(by), bz)
    bz_south = np.maximum(-bz, 0.0)

    out["P_dyn_nPa"] = 1.6726e-6 * np_density * vp**2
    out["Ey_mV/m"] = vp * bz_south * 1e-3
    alfven_speed = 21.8 * bt / np.sqrt(np_density.replace(0, np.nan))
    out["Ma"] = vp / alfven_speed.replace(0, np.nan)
    out["epsilon_norm"] = (vp * bt**2 * np.sin(clock / 2.0) ** 4).replace([np.inf, -np.inf], np.nan)
    out["Newell"] = (vp ** (4.0 / 3.0)) * (transverse ** (2.0 / 3.0)) * (np.sin(clock / 2.0) ** (8.0 / 3.0))
    out["Borovsky"] = out["P_dyn_nPa"] * out["Ey_mV/m"]
    return out


def build_dataset(args: argparse.Namespace) -> pd.DataFrame:
    solar = rename_aliases(read_table(args.solar), ["Btot", "Bx_gse", "By_gse", "Bz_gse", "Vp", "Np"])
    gic = rename_aliases(read_table(args.gic), ["gic"])

    missing_solar = [c for c in ["Btot", "Bx_gse", "By_gse", "Bz_gse", "Vp", "Np"] if c not in solar.columns]
    if missing_solar:
        raise KeyError(f"Missing solar-wind columns after alias matching: {missing_solar}")
    if "gic" not in gic.columns:
        raise KeyError("Missing GIC column after alias matching: gic")

    solar_1min = to_1min(solar[["Btot", "Bx_gse", "By_gse", "Bz_gse", "Vp", "Np"]])
    gic_1min = to_1min(gic[["gic"]], how="absmax")

    index = pd.date_range(args.start, args.end, freq="1min")
    merged = pd.DataFrame(index=index)
    merged = merged.join(solar_1min.reindex(index))
    merged = merged.join(gic_1min.reindex(index))

    merged = add_solar_coupling(merged)

    for col in OUTPUT_COLUMNS:
        if col not in merged.columns:
            raise KeyError(f"Output column was not created: {col}")

    out = merged[OUTPUT_COLUMNS].copy()
    for col in out.columns:
        if col not in {"density_missing", "filled_by_model"}:
            out[col] = pd.to_numeric(out[col], errors="coerce").astype("float32")
    out["density_missing"] = out["density_missing"].fillna(1).astype("int8")
    out["filled_by_model"] = out["filled_by_model"].fillna(0).astype("int8")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    out.to_parquet(args.output)
    print(f"[build] shape={out.shape}, output={args.output}")
    return out


def parse_args() -> argparse.Namespace:
    root = project_root()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--solar", type=Path, default=root / "data" / "raw" / "ace_solar_wind_2012_2022.csv")
    parser.add_argument("--gic", type=Path, default=root / "data" / "interim" / "vkh_gic_2012_2022_1min.parquet")
    parser.add_argument("--output", type=Path, default=root / "data" / "merged_2012_2022_processed.parquet")
    parser.add_argument("--start", default="2012-01-01 00:00:00")
    parser.add_argument("--end", default="2022-12-31 23:59:00")
    return parser.parse_args()


def main() -> None:
    build_dataset(parse_args())


if __name__ == "__main__":
    main()
